const dictionary = {
  "сонце":    "☀️",
  "хмара":    "☁️",
  "дощ":      "🌧️",
  "сніг":     "❄️",
  "блискавка":"⚡",
  "серце":    "❤️",
  "усмішка":  "😊",
  "сум":      "😢",
  "сміх":     "😂",
  "кава":     "☕",
  "піца":     "🍕",
  "яблуко":   "🍎",
  "собака":   "🐶",
  "кіт":      "🐱",
  "книга":    "📚",
  "телефон":  "📱",
  "комп":     "💻",
};

/**
 * Перекладає слова в тексті на емодзі.
 *
 * - Case-insensitive: "СОНЦЕ", "Сонце", "сонце" → "☀️"
 * - Розділові знаки зберігаються: "сонце," → "☀️,"
 * - Слова, яких немає у словнику, лишаються без змін
 *
 * translate("сьогодні сонце і усмішка")
 * // "сьогодні ☀️ і 😊"
 */
function translate(text) {
  let words = text.split(/(\s+)/);
    for (let i = 0; i < words.length; i++) {
        let word = words[i].toLowerCase().replace(/[.,!?;:()]/g, '');
        if (dictionary[word]) {
            words[i] = words[i].replace(new RegExp(word, 'i'), dictionary[word]);
        }
    }
    return words.join('');
}

translate("сьогодні сонце? і усміШка");
translate("СОНЦЕ і Хмара. Дощ?");
/**
 * Зворотний переклад: емодзі → слово (українською).
 */
function translateReverse(text) {
    let words = text.split(/(\s+)/);
    for (let i = 0; i < words.length; i++) {
        let emoji = words[i];
        for (let key in dictionary) {
            if (dictionary[key] === emoji) {
                words[i] = key;
                break;
            }
        }
    }
    return words.join('');
}

